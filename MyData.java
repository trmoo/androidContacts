package com.example.homework04;

public class MyData {
    private String name, alias, phone;

    public MyData(String name, String alias, String phone) {
        this.name = name;
        this.alias = alias;
        this.phone = phone;
    }

    public String getName() {
        return name;
    }

    public String getAlias() {
        return alias;
    }

    public String getPhone() {
        return phone;
    }
}
